    ap=argparse.ArgumentParser();ap.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1]);a=ap.parse_args();root=a.root
    pre=root/'evidence/official_only_repeat_preview';rr=tab(pre/'EXACT_REPEAT_GROUPS.tsv');ww=tab(pre/'RECURRENCE_CODING_CONTEXT.tsv');c={x['sequence_id']+'::'+x['region_id']:x for x in tab(root/'inputs/candidates.tsv')};pol=json.loads((root/'config/METHOD_POLICY.json').read_text());d={x['accession']:x for x in tab(root/'inputs/genome_sources.tsv')};dna={acc:seq(root/'inputs/genomes'/f'{acc}.fna') for acc in d};features=defaultdict(list)
    for r in tab(root/'inputs/all_official_features.tsv'):
        if r['feature_type']=='CDS':features[r['sequence_id']]+=json.loads(r['parts_json'])
    assert len(ww)==383 and {x['candidate_key'] for x in ww}==set(c)
    assert len({x['repeat_group_id'] for x in rr})==len(rr)
    copies=0
    for r in rr:
        acc=r['sequence_id'];ca=c[r['candidate_key']];aa=json.loads(r['copy_intervals_json']);motif=r['repeat_core_nt'];L=int(r['core_length_nt']);assert len(motif)==L and 12<=L<=64
