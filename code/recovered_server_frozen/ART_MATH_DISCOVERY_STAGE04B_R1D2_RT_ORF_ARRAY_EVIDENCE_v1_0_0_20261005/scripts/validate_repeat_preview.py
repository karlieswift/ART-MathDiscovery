#!/usr/bin/env python3
"""Independently verify every emitted repeat copy and every 0-based interval.

No RT or ORF result is generated by this script. The preview is a deterministic
exact-core repeat survey against existing CDS annotations, not an ART classifier.
"""
from pathlib import Path
from collections import Counter,defaultdict
import argparse,csv,json,hashlib

def tab(p):
    with Path(p).open() as f:return list(csv.DictReader(f,delimiter='\t'))
def seq(p):
    with Path(p).open() as f:return ''.join(x.strip() for x in f if not x.startswith('>')).upper()
def cov(a,b,parts):
    hits=sorted((max(a,x),min(b,y)) for x,y in parts if x<b and y>a)
    total=0;end=a
    for x,y in hits:
        total+=max(0,y-max(x,end));end=max(end,y)
    return total

